def detect_domains(text: str) -> list[str]:
    """从一段文本（策略思路/正文）里识别涉及的领域。"""
    hits: dict[str, int] = {}
    for domain, kws in DOMAIN_KEYWORDS.items():
        score = sum(1 for kw in kws if kw and kw in (text or ""))
        if score:
            hits[domain] = score
    return [d for d, _ in sorted(hits.items(), key=lambda kv: -kv[1])]


def canonical(value: str | None, allowed: list[str], fallback: str) -> str:
    """把任意字符串规约到标准取值；含「/·／」别名按「/」统一后匹配。"""
    if not value:
        return fallback
    v = str(value).strip().replace("·", "/").replace("／", "/").replace(" ", "")
    for a in allowed:
        if v == a.replace("/", "").replace(" ", ""):
            return a
    for a in allowed:
        if a in v or v in a:
            return a
    return fallback
